async def publish_charter(
    session: AsyncSession,
    current_user: CurrentUser,
    charter_id: UUID,
    *,
    reason: str | None = None,
    require_publish_permission: bool = True,
    auto: bool = False,
) -> ProjectCharter:
    """Publish an approved charter into Knowledge. Never rolls back approval."""
    if not is_charter_knowledge_publish_enabled():
        raise ApiError(
            409,
            "CHARTER_PUBLISH_DISABLED",
            "Governance charter Knowledge publication is disabled.",
        )
    if require_publish_permission:
        assert_can_publish_charter(current_user)

    charter = await get_project_charter_or_404(session, charter_id, current_user)
    if charter.status != GovernanceCharterStatus.APPROVED:
        raise ApiError(
            409,
            "CHARTER_NOT_APPROVED",
            "Only approved charters can be published to Knowledge.",
        )

    if (
        charter.publication_status == GovernanceCharterPublicationStatus.PUBLISHED
        and charter.knowledge_document_id
        and charter.knowledge_version_id
    ):
        await _record_publication_event(
            session,
            charter=charter,
            event_type=GovernanceCharterPublicationEventType.ALREADY_PUBLISHED,
            actor_user_id=current_user.id,
            knowledge_document_id=charter.knowledge_document_id,
            knowledge_version_id=charter.knowledge_version_id,
            reason=reason or "Duplicate publish attempt",
        )
        await _record_publication_audit(
            session,
            charter=charter,
            action="already_published",
            actor_user_id=current_user.id,
            knowledge_document_id=charter.knowledge_document_id,
            knowledge_version_id=charter.knowledge_version_id,
            reason=reason or "Duplicate publish attempt",
        )
        await log_governance_event(
            session,
            current_user,
            event_type="charter.publication_already_published",
            org_id=charter.org_id,
            project_id=charter.project_id,
            source_table="project_charters",
            source_id=charter.id,
            metadata={
                "knowledge_document_id": str(charter.knowledge_document_id),
                "knowledge_version_id": str(charter.knowledge_version_id),
                "auto": auto,
            },
        )
        await session.commit()
        raise ApiError(
            409,
            "ALREADY_PUBLISHED",
            "This charter version has already been published to Knowledge.",
            {
                "charter_id": str(charter.id),
                "knowledge_document_id": str(charter.knowledge_document_id),
                "knowledge_version_id": str(charter.knowledge_version_id),
            },
        )

    now = datetime.now(timezone.utc)
    charter.publication_status = GovernanceCharterPublicationStatus.PUBLISHING
    charter.publication_error = None
    charter.publication_attempt_count = (charter.publication_attempt_count or 0) + 1
    charter.last_publication_attempt_at = now
    await session.flush()

    try:
        project = await get_visible_project(session, charter.project_id, current_user)
        names = await load_user_names(
            session, {charter.approved_by} if charter.approved_by else set()
        )
        approved_by_name = names.get(charter.approved_by) if charter.approved_by else None
        markdown = build_knowledge_charter_markdown(
            project_name=project.name,
            project_id=project.id,
            charter=charter,
            approved_by_name=approved_by_name,
            department=project.vertical,
            client=None,
        )
        file_bytes = markdown.encode("utf-8")
        title = knowledge_document_title_for_project(project.name)
        effective = (
            charter.approved_at.date() if charter.approved_at else date.today()
        )
        owner = approved_by_name or current_user.email or "Governance Agent"

        previous_active_version_id = None
        if charter.knowledge_document_id:
            existing_doc = (
                await session.execute(
                    select(KnowledgeDocument).where(
                        KnowledgeDocument.id == charter.knowledge_document_id
                    )
                )
            ).scalar_one_or_none()
            if existing_doc and existing_doc.active_version_id:
                previous_active_version_id = existing_doc.active_version_id

        # Reuse Knowledge upload path (same title+folder → new version + supersede).
        read = await create_document_from_upload(
            session,
            current_user,
            folder_kind=KnowledgeFolderKind.HISTORIES,
            title=title,
            source_type=KnowledgeSourceType.PROJECT_CHARTER,
            version=charter.version,
            visibility=charter.visibility,
            status=KnowledgeDocumentStatus.DRAFT,
            owner_approver=owner,
            description=(
                f"Approved project charter {charter.version} published from Governance."
            ),
            approver=owner,
            project=project.name,
            department=project.vertical,
            effective_date=effective,
            file_name=f"{project.name.replace(' ', '_')}_charter_{charter.version}.md",
            file_mime_type="text/markdown",
            file_bytes=file_bytes,
        )
        if read.active_version_id is None:
            raise ApiError(500, "INTERNAL_ERROR", "Published document missing active version.")

        await _approve_knowledge_document_for_governance(
            session,
            current_user,
            read.id,
            effective_date=effective,
            note=(
                "Approved via Governance charter publication "
                f"(charter_id={charter.id}, version={charter.version})."
            ),
        )

        job = await enqueue_knowledge_ingestion_job(
            session, read.id, read.active_version_id
        )

        charter.knowledge_document_id = read.id
        charter.knowledge_version_id = read.active_version_id
        charter.publication_status = GovernanceCharterPublicationStatus.PUBLISHED
        charter.published_at = now
        charter.published_by = current_user.id
        charter.publication_error = None

        superseded = await _supersede_previous_project_publications(
            session, charter=charter, actor_user_id=current_user.id
        )

        await _record_publication_event(
            session,
            charter=charter,
            event_type=GovernanceCharterPublicationEventType.CHARTER_PUBLISHED,
            actor_user_id=current_user.id,
            knowledge_document_id=read.id,
            knowledge_version_id=read.active_version_id,
            previous_knowledge_version_id=previous_active_version_id,
            reason=reason or ("Auto-publish after approval" if auto else "Manual publish"),
            metadata={
                "auto": auto,
                "ingestion_job_id": str(job.id),
                "superseded_charter_ids": [str(x) for x in superseded],
            },
        )
        await _record_publication_event(
            session,
            charter=charter,
            event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_VERSION_CREATED,
            actor_user_id=current_user.id,
            knowledge_document_id=read.id,
            knowledge_version_id=read.active_version_id,
            previous_knowledge_version_id=previous_active_version_id,
            reason=reason,
            metadata={"knowledge_version": read.version},
        )
        await _record_publication_audit(
            session,
            charter=charter,
            action="publish",
            actor_user_id=current_user.id,
            knowledge_document_id=read.id,
            knowledge_version_id=read.active_version_id,
            previous_knowledge_version_id=previous_active_version_id,
            reason=reason or ("Auto-publish after approval" if auto else "Manual publish"),
            metadata={"auto": auto, "ingestion_job_id": str(job.id)},
        )
        await log_governance_event(
            session,
            current_user,
            event_type="charter.published",
            org_id=charter.org_id,
            project_id=charter.project_id,
            source_table="project_charters",
            source_id=charter.id,
            new_values={
                "publication_status": charter.publication_status.value,
                "knowledge_document_id": str(read.id),
                "knowledge_version_id": str(read.active_version_id),
            },
            metadata={"auto": auto, "reason": reason},
        )
        await session.commit()
        await session.refresh(charter)
        invalidate_project_charter_list_cache(org_id=charter.org_id, project_id=charter.project_id)
        dispatch_knowledge_ingestion_job(session, job.id)
        return charter
    except ApiError as exc:
        if exc.code == "ALREADY_PUBLISHED":
            raise
        await session.rollback()
        charter = await get_project_charter_or_404(session, charter_id, current_user)
        charter.publication_status = GovernanceCharterPublicationStatus.FAILED
        charter.publication_error = str(exc.message)
        charter.last_publication_attempt_at = datetime.now(timezone.utc)
        await _record_publication_event(
            session,
            charter=charter,
            event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_PUBLICATION_FAILED,
            actor_user_id=current_user.id,
            reason=str(exc.message),
            metadata={"code": exc.code, "auto": auto},
        )
        await _record_publication_audit(
            session,
            charter=charter,
            action="publication_failed",
            actor_user_id=current_user.id,
            reason=str(exc.message),
            metadata={"code": exc.code, "auto": auto},
        )
        await log_governance_event(
            session,
            current_user,
            event_type="charter.publication_failed",
            org_id=charter.org_id,
            project_id=charter.project_id,
            source_table="project_charters",
            source_id=charter.id,
            metadata={"error": str(exc.message), "auto": auto},
        )
        await session.commit()
        await session.refresh(charter)
        invalidate_project_charter_list_cache(org_id=charter.org_id, project_id=charter.project_id)
        raise
    except Exception as exc:  # noqa: BLE001 — publish must never roll back approval
        logger.exception("Charter knowledge publication failed for %s", charter_id)
        await session.rollback()
        charter = await get_project_charter_or_404(session, charter_id, current_user)
        charter.publication_status = GovernanceCharterPublicationStatus.FAILED
        charter.publication_error = str(exc)
        charter.last_publication_attempt_at = datetime.now(timezone.utc)
        await _record_publication_event(
            session,
            charter=charter,
            event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_PUBLICATION_FAILED,
            actor_user_id=current_user.id,
            reason=str(exc),
            metadata={"auto": auto},
        )
        await _record_publication_audit(
            session,
            charter=charter,
            action="publication_failed",
            actor_user_id=current_user.id,
            reason=str(exc),
            metadata={"auto": auto},
        )
        try:
            await log_governance_event(
                session,
                current_user,
                event_type="charter.publication_failed",
                org_id=charter.org_id,
                project_id=charter.project_id,
                source_table="project_charters",
                source_id=charter.id,
                metadata={"error": str(exc), "auto": auto},
            )
        except Exception:  # noqa: BLE001
            logger.exception("Failed to audit charter publication failure")
        await session.commit()
        await session.refresh(charter)
        invalidate_project_charter_list_cache(org_id=charter.org_id, project_id=charter.project_id)
        raise ApiError(
            500,
            "CHARTER_PUBLICATION_FAILED",
            "Charter approval is preserved, but Knowledge publication failed.",
            {
                "charter_id": str(charter.id),
                "publication_status": charter.publication_status.value,
                "error": str(exc),
            },
        ) from exc


async def retry_publication(
    session: AsyncSession,
    current_user: CurrentUser,
    charter_id: UUID,
    *,
    reason: str | None = None,
) -> ProjectCharter:
    assert_can_publish_charter(current_user)
    charter = await get_project_charter_or_404(session, charter_id, current_user)
    if charter.publication_status not in {
        GovernanceCharterPublicationStatus.FAILED,
        GovernanceCharterPublicationStatus.NOT_PUBLISHED,
        GovernanceCharterPublicationStatus.PUBLISHING,
    }:
        if charter.publication_status == GovernanceCharterPublicationStatus.PUBLISHED:
            raise ApiError(
                409,
                "ALREADY_PUBLISHED",
                "This charter version has already been published to Knowledge.",
            )
        raise ApiError(
            409,
            "CHARTER_NOT_RETRYABLE",
            "Only failed or unpublished charters can retry publication.",
        )
    await _record_publication_event(
        session,
        charter=charter,
        event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_PUBLICATION_RETRIED,
        actor_user_id=current_user.id,
        reason=reason or "Retry publication",
    )
    await _record_publication_audit(
        session,
        charter=charter,
        action="retry_publication",
        actor_user_id=current_user.id,
        reason=reason or "Retry publication",
    )
    await session.flush()
    return await publish_charter(
        session,
        current_user,
        charter_id,
        reason=reason or "Retry publication",
        require_publish_permission=False,
        auto=False,
    )


async def republish_charter(
    session: AsyncSession,
    current_user: CurrentUser,
    charter_id: UUID,
    *,
    reason: str | None = None,
) -> ProjectCharter:
    """Refresh indexing/metadata for an already-published charter version."""
    assert_can_publish_charter(current_user)
    if not is_charter_knowledge_publish_enabled():
        raise ApiError(
            409,
            "CHARTER_PUBLISH_DISABLED",
            "Governance charter Knowledge publication is disabled.",
        )
    charter = await get_project_charter_or_404(session, charter_id, current_user)
    if charter.publication_status != GovernanceCharterPublicationStatus.PUBLISHED:
        raise ApiError(
            409,
            "CHARTER_NOT_PUBLISHED",
            "Only published charters can be republished.",
        )
    if not charter.knowledge_document_id:
        raise ApiError(
            409,
            "CHARTER_MISSING_KNOWLEDGE_DOCUMENT",
            "Published charter is missing its Knowledge document link.",
        )

    now = datetime.now(timezone.utc)
    charter.publication_attempt_count = (charter.publication_attempt_count or 0) + 1
    charter.last_publication_attempt_at = now
    previous_version_id = charter.knowledge_version_id

    try:
        read = await reindex_document(session, current_user, charter.knowledge_document_id)
        if read.active_version_id is None:
            raise ApiError(500, "INTERNAL_ERROR", "Republished document missing active version.")
        job = await enqueue_knowledge_ingestion_job(
            session, read.id, read.active_version_id
        )
        charter.knowledge_version_id = read.active_version_id
        charter.publication_error = None
        await _record_publication_event(
            session,
            charter=charter,
            event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_REPUBLISHED,
            actor_user_id=current_user.id,
            knowledge_document_id=read.id,
            knowledge_version_id=read.active_version_id,
            previous_knowledge_version_id=previous_version_id,
            reason=reason or "Republish for reindex/metadata refresh",
            metadata={"ingestion_job_id": str(job.id)},
        )
        await _record_publication_audit(
            session,
            charter=charter,
            action="republish",
            actor_user_id=current_user.id,
            knowledge_document_id=read.id,
            knowledge_version_id=read.active_version_id,
            previous_knowledge_version_id=previous_version_id,
            reason=reason or "Republish for reindex/metadata refresh",
        )
        await log_governance_event(
            session,
            current_user,
            event_type="charter.republished",
            org_id=charter.org_id,
            project_id=charter.project_id,
            source_table="project_charters",
            source_id=charter.id,
            metadata={"reason": reason, "knowledge_document_id": str(read.id)},
        )
        await session.commit()
        await session.refresh(charter)
        invalidate_project_charter_list_cache(org_id=charter.org_id, project_id=charter.project_id)
        dispatch_knowledge_ingestion_job(session, job.id)
        return charter
    except Exception as exc:  # noqa: BLE001
        logger.exception("Charter republish failed for %s", charter_id)
        await session.rollback()
        charter = await get_project_charter_or_404(session, charter_id, current_user)
        charter.publication_error = str(exc)
        charter.last_publication_attempt_at = datetime.now(timezone.utc)
        await _record_publication_event(
            session,
            charter=charter,
            event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_PUBLICATION_FAILED,
            actor_user_id=current_user.id,
            reason=str(exc),
            metadata={"action": "republish"},
        )
        await session.commit()
        invalidate_project_charter_list_cache(org_id=charter.org_id, project_id=charter.project_id)
        raise ApiError(
            500,
            "CHARTER_REPUBLISH_FAILED",
            "Republish failed; prior published Knowledge version remains available.",
            {"charter_id": str(charter.id), "error": str(exc)},
        ) from exc


async def unpublish_charter(
    session: AsyncSession,
    current_user: CurrentUser,
    charter_id: UUID,
    *,
    reason: str | None = None,
) -> ProjectCharter:
    """Soft-unpublish: clear publish linkage status without deleting Knowledge history."""
    assert_can_publish_charter(current_user)
    charter = await get_project_charter_or_404(session, charter_id, current_user)
    if charter.publication_status == GovernanceCharterPublicationStatus.NOT_PUBLISHED:
        return charter

    previous_doc = charter.knowledge_document_id
    previous_version = charter.knowledge_version_id
    charter.publication_status = GovernanceCharterPublicationStatus.NOT_PUBLISHED
    charter.published_at = None
    charter.published_by = None
    charter.publication_error = None
    # Retain knowledge_document_id for historical deep links; status reflects unpublished.
    await _record_publication_event(
        session,
        charter=charter,
        event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_UNPUBLISHED,
        actor_user_id=current_user.id,
        knowledge_document_id=previous_doc,
        knowledge_version_id=previous_version,
        reason=reason or "Unpublished from Governance",
    )
    await _record_publication_audit(
        session,
        charter=charter,
        action="unpublish",
        actor_user_id=current_user.id,
        knowledge_document_id=previous_doc,
        knowledge_version_id=previous_version,
        reason=reason or "Unpublished from Governance",
    )
    await log_governance_event(
        session,
        current_user,
        event_type="charter.unpublished",
        org_id=charter.org_id,
        project_id=charter.project_id,
        source_table="project_charters",
        source_id=charter.id,
        metadata={"reason": reason},
    )
    await session.commit()
    await session.refresh(charter)
    invalidate_project_charter_list_cache(org_id=charter.org_id, project_id=charter.project_id)
    return charter


async def maybe_auto_publish_after_approval(
    session: AsyncSession,
    current_user: CurrentUser,
    charter: ProjectCharter,
) -> ProjectCharter:
    """Best-effort publish after approval. Never raises; never rolls back approval."""
    if not is_auto_publish_approved_charters_enabled():
        return charter
    if charter.status != GovernanceCharterStatus.APPROVED:
        return charter
    try:
        return await publish_charter(
            session,
            current_user,
            charter.id,
            reason="Auto-publish after approval",
            require_publish_permission=False,
            auto=True,
        )
    except ApiError as exc:
        if exc.code == "ALREADY_PUBLISHED":
            refreshed = await get_project_charter_or_404(session, charter.id, current_user)
            return refreshed
        logger.warning(
            "Auto-publish after approval failed for charter %s: %s",
            charter.id,
            exc.message,
        )
        refreshed = await get_project_charter_or_404(session, charter.id, current_user)
        return refreshed
    except Exception:  # noqa: BLE001
        logger.exception("Auto-publish after approval failed for charter %s", charter.id)
        refreshed = await get_project_charter_or_404(session, charter.id, current_user)
        return refreshed
