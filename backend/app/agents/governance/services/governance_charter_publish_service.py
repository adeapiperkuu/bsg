async def _approve_knowledge_document_for_governance(
    session: AsyncSession,
    current_user: CurrentUser,
    document_id: UUID,
    *,
    effective_date: date,
    note: str,
) -> KnowledgeDocument:
    """Mark Knowledge doc approved after Governance charter approval (HITL already done)."""
    doc = (
        await session.execute(
            select(KnowledgeDocument).where(
                KnowledgeDocument.id == document_id,
                KnowledgeDocument.org_id == current_user.org_id,
                KnowledgeDocument.deleted_at.is_(None),
            )
        )
    ).scalar_one_or_none()
    if doc is None:
        raise ApiError(404, "NOT_FOUND", "Knowledge document was not found.")

    previous = doc.status
    now = datetime.now(timezone.utc)
    doc.effective_date = effective_date
    doc.status = KnowledgeDocumentStatus.APPROVED
    doc.submitted_by = doc.submitted_by or current_user.id
    doc.submitted_at = doc.submitted_at or now
    doc.reviewed_by = current_user.id
    doc.reviewed_at = now
    doc.approved_by = current_user.id
    doc.approved_at = now
    doc.rejection_reason = None
    if doc.active_version_id:
        version = (
            await session.execute(
                select(KnowledgeDocumentVersion).where(
                    KnowledgeDocumentVersion.id == doc.active_version_id
                )
            )
        ).scalar_one_or_none()
        if version is not None:
            version.approved_by = current_user.id
            version.approved_at = now

    session.add(
        KnowledgeDocumentApprovalEvent(
            org_id=doc.org_id,
            document_id=doc.id,
            actor_id=current_user.id,
            from_status=previous.value if previous else None,
            to_status=doc.status.value,
            action="approve",
            note=note,
        )
    )
    await session.flush()
    return doc


async def _supersede_previous_project_publications(
    session: AsyncSession,
    *,
    charter: ProjectCharter,
    actor_user_id: UUID | None,
) -> list[UUID]:
    """Mark older published charters for the same project as superseded (never delete)."""
    rows = list(
        (
            await session.execute(
                select(ProjectCharter).where(
                    ProjectCharter.project_id == charter.project_id,
                    ProjectCharter.id != charter.id,
                    ProjectCharter.publication_status
                    == GovernanceCharterPublicationStatus.PUBLISHED,
                )
            )
        )
        .scalars()
        .all()
    )
    superseded_ids: list[UUID] = []
    for row in rows:
        row.publication_status = GovernanceCharterPublicationStatus.SUPERSEDED
        superseded_ids.append(row.id)
        await _record_publication_event(
            session,
            charter=row,
            event_type=GovernanceCharterPublicationEventType.KNOWLEDGE_VERSION_SUPERSEDED,
            actor_user_id=actor_user_id,
            knowledge_document_id=row.knowledge_document_id,
            knowledge_version_id=row.knowledge_version_id,
            reason=f"Superseded by charter {charter.version}",
            metadata={"superseded_by_charter_id": str(charter.id)},
        )
        await _record_publication_audit(
            session,
            charter=row,
            action="version_superseded",
            actor_user_id=actor_user_id,
            knowledge_document_id=row.knowledge_document_id,
            knowledge_version_id=row.knowledge_version_id,
            reason=f"Superseded by charter {charter.version}",
        )
    return superseded_ids


