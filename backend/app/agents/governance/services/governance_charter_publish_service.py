PUBLISH_ROLES = {AppRole.BSG_LEADERSHIP, AppRole.SUPER_ADMIN}
CHARTER_KNOWLEDGE_TITLE_SUFFIX = "— Project Charter"
APPROVAL_SECTION_PATTERN = re.compile(
    r"(##\s*Approval Section\b)([\s\S]*?)(?=\n##\s|\Z)",
    re.IGNORECASE,
)


def assert_can_publish_charter(current_user: CurrentUser) -> None:
    if current_user.role not in PUBLISH_ROLES:
        raise ApiError(
            403,
            "FORBIDDEN",
            "Only Leadership or Super Admin may publish charters to Knowledge.",
        )


def is_charter_knowledge_publish_enabled() -> bool:
    return bool(get_settings().governance_charter_knowledge_publish_enabled)


def is_auto_publish_approved_charters_enabled() -> bool:
    settings = get_settings()
    return bool(
        settings.governance_charter_knowledge_publish_enabled
        and settings.auto_publish_approved_charters
    )


def knowledge_document_title_for_project(project_name: str) -> str:
    cleaned = " ".join((project_name or "Project").split())
    return f"{cleaned} {CHARTER_KNOWLEDGE_TITLE_SUFFIX}"


def knowledge_deep_link(document_id: UUID | None) -> str | None:
    if document_id is None:
        return None
    return f"/knowledge?documentId={document_id}"


def build_knowledge_charter_markdown(
    *,
    project_name: str,
    project_id: UUID,
    charter: ProjectCharter,
    approved_by_name: str | None,
    department: str | None = None,
    client: str | None = None,
) -> str:
    """Build clean Knowledge markdown (never raw DB JSON)."""
    body = sanitize_charter_text(charter.generated_text).strip()
    approval_date = (
        charter.approved_at.date().isoformat()
        if charter.approved_at
        else date.today().isoformat()
    )
    approved_by = approved_by_name or (
        str(charter.approved_by) if charter.approved_by else "Unknown"
    )

    def _fill_approval(match: re.Match[str]) -> str:
        return (
            f"{match.group(1)}\n"
            f"- Generated by: AI Project Governance Agent\n"
            f"- Reviewed by: {approved_by}\n"
            f"- Approved by: {approved_by}\n"
            f"- Approval date: {approval_date}\n"
            f"- Version: {charter.version}\n"
            f"- Status: approved\n"
            f"- Source: governance\n"
        )

    if APPROVAL_SECTION_PATTERN.search(body):
        body = APPROVAL_SECTION_PATTERN.sub(_fill_approval, body)
    else:
        body = (
            f"{body}\n\n## Approval Section\n"
            f"- Generated by: AI Project Governance Agent\n"
            f"- Reviewed by: {approved_by}\n"
            f"- Approved by: {approved_by}\n"
            f"- Approval date: {approval_date}\n"
            f"- Version: {charter.version}\n"
            f"- Status: approved\n"
            f"- Source: governance\n"
        )

    # Strip a leading H1 so Knowledge content has a single document title.
    body = re.sub(r"^#\s+Project Charter\s*\n+", "", body, count=1, flags=re.IGNORECASE)

    meta_lines = [
        "- document_type: project_charter",
        f"- project_id: {project_id}",
        f"- project_name: {project_name}",
        f"- client: {client or 'n/a'}",
        f"- department: {department or 'n/a'}",
        f"- charter_id: {charter.id}",
        f"- charter_version: {charter.version}",
        f"- approval_date: {approval_date}",
        f"- approved_by: {approved_by}",
        f"- effective_date: {approval_date}",
        "- status: approved",
        "- source: governance",
        "- created_from: project_charter",
        "- confidence: 100",
        f"- visibility: {charter.visibility.value}",
        f"- tags: project_charter, governance, {project_name}",
    ]
    return (
        "# Project Charter\n\n"
        "## Document Metadata\n"
        + "\n".join(meta_lines)
        + "\n\n"
        + body
    )


async def _record_publication_event(
    session: AsyncSession,
    *,
    charter: ProjectCharter,
    event_type: GovernanceCharterPublicationEventType,
    actor_user_id: UUID | None,
    knowledge_document_id: UUID | None = None,
    knowledge_version_id: UUID | None = None,
    previous_knowledge_version_id: UUID | None = None,
    reason: str | None = None,
    metadata: dict[str, Any] | None = None,
) -> GovernanceCharterPublicationEvent:
    event = GovernanceCharterPublicationEvent(
        org_id=charter.org_id,
        charter_id=charter.id,
        project_id=charter.project_id,
        event_type=event_type,
        actor_user_id=actor_user_id,
        knowledge_document_id=knowledge_document_id,
        knowledge_version_id=knowledge_version_id,
        previous_knowledge_version_id=previous_knowledge_version_id,
        charter_version=charter.version,
        reason=reason,
        event_metadata=metadata or {},
    )
    session.add(event)
    return event


